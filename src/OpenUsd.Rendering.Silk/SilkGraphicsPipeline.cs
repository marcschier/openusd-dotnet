            new(SilkVertexSemantic.Position, 0, 0, SilkVertexFormat.Float3),
            new(SilkVertexSemantic.Normal, 1, 12, SilkVertexFormat.Float3),
            new(SilkVertexSemantic.TexCoord, 2, 24, SilkVertexFormat.Float2)
        ]);

    /// <summary>Gets the checked POSITION/NORMAL/TEXCOORD/TANGENT layout.</summary>
    internal static SilkVertexLayoutDescriptor PositionNormalTexCoordTangent => new(
        48,
        [
            new(SilkVertexSemantic.Position, 0, 0, SilkVertexFormat.Float3),
            new(SilkVertexSemantic.Normal, 1, 12, SilkVertexFormat.Float3),
            new(SilkVertexSemantic.TexCoord, 2, 24, SilkVertexFormat.Float2),
            new(SilkVertexSemantic.Tangent, 3, 32, SilkVertexFormat.Float4)
        ]);

    /// <summary>Validates the checked mesh vertex layout.</summary>
    public void Validate()
    {
        ArgumentNullException.ThrowIfNull(Attributes);
        if (!Matches(PositionNormal) &&
            !Matches(PositionNormalTexCoord) &&
            !Matches(PositionNormalTexCoordTangent))
        {
            throw new ArgumentException(
                "The checked mesh shader requires a known position/normal layout, optionally with UV and tangent.",
                nameof(Attributes));
        }
    }

    private bool Matches(SilkVertexLayoutDescriptor expected)
    {
        if (Stride != expected.Stride || Attributes.Count != expected.Attributes.Count)
        {
            return false;
        }
        for (int index = 0; index < Attributes.Count; index++)
        {
            if (Attributes[index] != expected.Attributes[index])
            {
                return false;
            }
        }
        return true;
    }
}

/// <summary>Face-culling mode supported by Silk mesh pipelines.</summary>
/// <remarks>
/// Every backend rasterizes with counter-clockwise front faces, and hdSilk
/// normalises an authored <c>leftHanded</c> orientation into that convention
/// before the page, so "front" and "back" mean the same thing on all of them.
/// </remarks>
public enum SilkCullMode
{
    /// <summary>Rasterizes front- and back-facing triangles.</summary>
    None = 0,

    /// <summary>Culls back-facing triangles.</summary>
    Back = 1,

    /// <summary>Culls front-facing triangles.</summary>
    Front = 2
}

/// <summary>Color blending mode for a Silk graphics pipeline.</summary>
public enum SilkBlendMode
{
    /// <summary>Replaces the destination color.</summary>
    None = 0,

    /// <summary>Composites straight-alpha source color over the destination.</summary>
    StraightAlphaOver = 1
}

/// <summary>Describes a color/depth graphics pipeline.</summary>
