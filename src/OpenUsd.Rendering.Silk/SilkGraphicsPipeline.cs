/// <summary>The kind of resource occupying one binding slot.</summary>
public enum SilkBindingKind
{
    /// <summary>A uniform (constant) buffer.</summary>
    UniformBuffer = 0,

    /// <summary>A texture read through a sampler.</summary>
    SampledTexture = 1,

    /// <summary>A sampler.</summary>
    Sampler = 2,

    /// <summary>A read-only structured/storage buffer.</summary>
    StorageBuffer = 3
}

/// <summary>
/// One slot in a material binding layout.
/// </summary>
public readonly record struct SilkBindingSlot(
    uint Set,
    uint Binding,
    SilkBindingKind Kind,
    uint UniformByteSize,
    SilkShaderStageVisibility Visibility)
{
    /// <summary>Validates one slot in isolation.</summary>
    public void Validate()
    {
        if (Kind is not (SilkBindingKind.UniformBuffer or
            SilkBindingKind.SampledTexture or SilkBindingKind.Sampler or
            SilkBindingKind.StorageBuffer))
        {
            throw new ArgumentOutOfRangeException(
                nameof(Kind),
                "A binding slot kind must be uniform buffer, storage buffer, sampled texture, or sampler.");
        }
        if (Kind == SilkBindingKind.UniformBuffer)
        {
            if (UniformByteSize == 0 || (UniformByteSize % 16) != 0)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(UniformByteSize),
                    "A uniform buffer slot must be a non-zero multiple of 16 bytes.");
            }
        }
        else if (UniformByteSize != 0)
        {
            throw new ArgumentException(
                "Only a uniform buffer slot carries a byte size.",
                nameof(UniformByteSize));
        }
        if (Visibility == 0)
        {
            throw new ArgumentException(
                "A binding slot must be visible to at least one stage.",
                nameof(Visibility));
        }
    }
}

/// <summary>Reflected SceneParameters binding layout.</summary>
public readonly record struct SilkBindingLayoutDescriptor(
    uint Set,
    uint Binding,
    uint UniformByteSize,
    SilkShaderStageVisibility Visibility)
{
    /// <summary>
    /// Gets the additional material, instance, and frame-resource slots.
    /// </summary>
    /// <remarks>
    /// Additive on purpose. The renderer-neutral device interface is implemented by
    /// three backends and several test doubles, so widening the layout through this
    /// descriptor keeps every existing implementation and caller compiling unchanged
    /// while letting a material layout be described at all, which the single
    /// SceneParameters slot could not express.
    /// </remarks>
    public IReadOnlyList<SilkBindingSlot> MaterialSlots { get; init; } = [];

    /// <summary>The binding slot carrying the surface constants and the light.</summary>
    public const uint SurfaceParametersBinding = 7;

    /// <summary>The binding slot carrying per-frame projection and clip-plane data.</summary>
    public const uint FrameParametersBinding = 8;

    /// <summary>The sampler used by sampled density volumes.</summary>
    internal const uint VolumeSamplerBinding = 13;

    internal const uint BaseColorSamplerBinding = 1;
    internal const uint NormalSamplerBinding = 10;
    internal const uint RoughnessMetallicSamplerBinding = 11;
    internal const uint EmissiveSamplerBinding = 12;
    internal const uint BaseColorTextureBinding = 2;
    internal const uint NormalTextureBinding = 3;
    internal const uint RoughnessMetallicTextureBinding = 4;
    internal const uint EmissiveTextureBinding = 5;

    /// <summary>
    /// The sampler for the metallic texture. Metallic has its own slot rather than
    /// sharing the roughness slot, so a metallic-only material binds nothing to
    /// roughness and vice versa.
    /// </summary>
    internal const uint MetallicSamplerBinding = 14;

    /// <summary>The metallic texture. See <see cref="MetallicSamplerBinding"/>.</summary>
    internal const uint MetallicTextureBinding = 15;
    internal const uint OpacitySamplerBinding = 16;
    internal const uint OpacityTextureBinding = 17;
    internal const uint OcclusionSamplerBinding = 18;
    internal const uint OcclusionTextureBinding = 19;
    internal const uint SpecularColorSamplerBinding = 20;
    internal const uint SpecularColorTextureBinding = 21;
    internal const uint ClearcoatSamplerBinding = 22;
    internal const uint ClearcoatTextureBinding = 23;
    internal const uint ClearcoatRoughnessSamplerBinding = 24;
    internal const uint ClearcoatRoughnessTextureBinding = 25;
    internal const uint IorSamplerBinding = 26;
    internal const uint IorTextureBinding = 27;

    /// <summary>
    /// The sampler for the material's single composite image.
    /// </summary>
    /// <remarks>
    /// One universal slot, not one per material parameter: a per-parameter
    /// composite would need eleven more sampler/texture pairs, and every mesh
    /// pipeline would have to declare them. Which parameter it drives is a
    /// runtime value in the surface constants, so it adds no shader permutation.
    /// </remarks>
    internal const uint CompositeSamplerBinding = 28;

    /// <summary>The material's single composite image. See <see cref="CompositeSamplerBinding"/>.</summary>
    internal const uint CompositeTextureBinding = 29;

    /// <summary>The sampled 3D density texture used by volumes.</summary>
    internal const uint VolumeDensityTextureBinding = 9;

    private static IReadOnlyList<SilkBindingSlot> SharedMeshSlots =>
    [
        new(
            0,
            6,
            SilkBindingKind.StorageBuffer,
            0,
            SilkShaderStageVisibility.Vertex),
        new(
            0,
            SurfaceParametersBinding,
            SilkBindingKind.StorageBuffer,
            0,
            SilkShaderStageVisibility.Fragment),
        new(
            0,
            FrameParametersBinding,
            SilkBindingKind.StorageBuffer,
            0,
            SilkShaderStageVisibility.Vertex | SilkShaderStageVisibility.Fragment)
    ];

    private static SilkBindingSlot VolumeDensityTextureSlot => new(
        0,
        VolumeDensityTextureBinding,
        SilkBindingKind.SampledTexture,
        0,
        SilkShaderStageVisibility.Fragment);

    /// <summary>Creates the checked mesh SceneParameters layout.</summary>
    public static SilkBindingLayoutDescriptor SceneParameters => new(
        0,
        0,
        SilkCheckedShaderAssets.SceneParameters.ByteSize,
        SilkShaderStageVisibility.Vertex | SilkShaderStageVisibility.Fragment)
    {
        MaterialSlots =
        [
            .. SharedMeshSlots
        ]
    };

    internal static SilkBindingLayoutDescriptor SampledVolumeParameters => SceneParameters with
    {
        MaterialSlots =
        [
            .. SharedMeshSlots,
            new(
                0,
                VolumeSamplerBinding,
                SilkBindingKind.Sampler,
                0,
                SilkShaderStageVisibility.Fragment),
            VolumeDensityTextureSlot
        ]
    };

    internal static (uint Sampler, uint Texture) GetMaterialTextureBindings(
        SilkMaterialParameter parameter) =>
        parameter switch
        {
            SilkMaterialParameter.DiffuseColor =>
                (BaseColorSamplerBinding, BaseColorTextureBinding),
            SilkMaterialParameter.Normal =>
                (NormalSamplerBinding, NormalTextureBinding),
            SilkMaterialParameter.Roughness =>
                (RoughnessMetallicSamplerBinding, RoughnessMetallicTextureBinding),
            SilkMaterialParameter.Metallic =>
                (MetallicSamplerBinding, MetallicTextureBinding),
            SilkMaterialParameter.EmissiveColor =>
                (EmissiveSamplerBinding, EmissiveTextureBinding),
            SilkMaterialParameter.Opacity =>
                (OpacitySamplerBinding, OpacityTextureBinding),
            SilkMaterialParameter.Occlusion =>
                (OcclusionSamplerBinding, OcclusionTextureBinding),
            SilkMaterialParameter.SpecularColor =>
                (SpecularColorSamplerBinding, SpecularColorTextureBinding),
            SilkMaterialParameter.Clearcoat =>
                (ClearcoatSamplerBinding, ClearcoatTextureBinding),
            SilkMaterialParameter.ClearcoatRoughness =>
                (ClearcoatRoughnessSamplerBinding, ClearcoatRoughnessTextureBinding),
            SilkMaterialParameter.Ior =>
                (IorSamplerBinding, IorTextureBinding),
            _ => throw new ArgumentOutOfRangeException(
                nameof(parameter),
                parameter,
                "The material parameter does not have a 2D shader texture slot.")
        };

    /// <summary>Creates a material layout from its slots.</summary>
    public static SilkBindingLayoutDescriptor ForMaterial(
        IReadOnlyList<SilkBindingSlot> slots)
    {
        ArgumentNullException.ThrowIfNull(slots);
        if (slots.Count == 0)
        {
            throw new ArgumentException(
                "A material binding layout requires at least one slot.",
                nameof(slots));
        }
        // Slot 0 stays the SceneParameters uniform so a material pipeline keeps the
        // same scene constants at the same place as every existing pipeline. The
        // checked mesh shaders also always declare the instance buffer and the
        // surface constants, so both are carried into every material layout.
        IReadOnlyList<SilkBindingSlot> shared = SharedMeshSlots;
        var materialSlots = new SilkBindingSlot[slots.Count + shared.Count];
        for (int index = 0; index < shared.Count; index++)
        {
            materialSlots[index] = shared[index];
        }
        for (int index = 0; index < slots.Count; index++)
        {
            materialSlots[index + shared.Count] = slots[index];
        }
        return SceneParameters with { MaterialSlots = materialSlots };
    }

    /// <summary>Validates the layout.</summary>
    public void Validate()
    {
        if (Set != 0 || Binding != 0)
        {
            throw new ArgumentException("SceneParameters must use set 0, binding 0.");
        }
        if (UniformByteSize != 80)
        {
            throw new ArgumentOutOfRangeException(
                nameof(UniformByteSize),
                "SceneParameters must contain exactly 80 bytes.");
        }
        if (Visibility !=
            (SilkShaderStageVisibility.Vertex | SilkShaderStageVisibility.Fragment))
        {
            throw new ArgumentException(
                "SceneParameters must be visible to vertex and fragment stages.",
                nameof(Visibility));
        }
        IReadOnlyList<SilkBindingSlot> slots = MaterialSlots ?? [];
        for (int index = 0; index < slots.Count; index++)
        {
            SilkBindingSlot slot = slots[index];
            slot.Validate();
            if (slot.Set != 0)
            {
                // Every backend binds exactly one set today: Vulkan binds set 0, and
                // D3D12 and Metal have no set concept at all. Accepting a second set
                // would describe a binding no backend could ever reach.
                throw new ArgumentException(
                    "A material slot must use set 0, the only set the backends bind.");
            }
            if (slot.Set == 0 && slot.Binding == 0)
            {
                throw new ArgumentException(
                    "A material slot cannot occupy set 0, binding 0, which is SceneParameters.");
            }
            for (int other = 0; other < index; other++)
            {
                if (slots[other].Set == slot.Set && slots[other].Binding == slot.Binding)
                {
                    throw new ArgumentException(
                        $"Material slots collide at set {slot.Set}, binding {slot.Binding}.");
                }
            }
        }
    }

    /// <summary>
    /// Requires that a material slot of <paramref name="kind"/> exists at the given
    /// set and binding, and returns its index within
    /// <see cref="MaterialSlots"/>.
    /// </summary>
    /// <remarks>
    /// Every backend binds resources through this one check, so a slot mismatch fails
    /// identically everywhere instead of surfacing as a different backend-specific
    /// validation error, or worse, as a silently unbound resource.
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    /// No slot of that kind is declared at that set and binding.
    /// </exception>
    public int RequireMaterialSlot(uint set, uint binding, SilkBindingKind kind)
    {
        IReadOnlyList<SilkBindingSlot> slots = MaterialSlots ?? [];
        for (int index = 0; index < slots.Count; index++)
        {
            SilkBindingSlot slot = slots[index];
            if (slot.Set == set && slot.Binding == binding)
            {
                if (slot.Kind != kind)
                {
                    throw new InvalidOperationException(
                        $"Set {set}, binding {binding} is a {slot.Kind} slot, not a {kind} slot.");
                }
                return index;
            }
        }
        throw new InvalidOperationException(
            $"The bound pipeline declares no material slot at set {set}, binding {binding}.");
    }
}

