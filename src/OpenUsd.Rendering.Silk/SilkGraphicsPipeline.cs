/// <summary>Thread-safe checked mesh graphics pipeline cache for one Silk device.</summary>
public sealed class SilkGraphicsPipelineCache : IDisposable
{
    private readonly object _gate = new();
    private readonly ISilkGraphicsDevice _device;
    private readonly SilkShaderBinaryFormat _shaderFormat;
    private readonly Dictionary<PipelineCacheKey, CachedPipelineEntry> _entries = [];
    private DeviceGenerationKey _generation;
    private bool _disposed;

    /// <summary>Initializes a cache for one graphics device and shader binary format.</summary>
    public SilkGraphicsPipelineCache(
        ISilkGraphicsDevice device,
        SilkShaderBinaryFormat shaderFormat)
    {
        ArgumentNullException.ThrowIfNull(device);
        if (!Enum.IsDefined(shaderFormat))
        {
            throw new ArgumentOutOfRangeException(nameof(shaderFormat));
        }

        _device = device;
        _shaderFormat = shaderFormat;
        _generation = ReadDeviceGeneration(device);
    }

    /// <summary>Gets or creates a shared checked mesh pipeline.</summary>
    public ISilkGraphicsPipeline GetOrCreateMeshPipeline(
        SilkShaderPermutationId permutation,
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode = SilkCullMode.None,
        SilkTopologyKind topologyKind = SilkTopologyKind.TriangleList) =>
        GetOrCreateMeshPipelineWithState(
            permutation,
            vertexLayout,
            colorFormat,
            depthFormat,
            cullMode,
            topologyKind,
            SilkBlendMode.None,
            depthWriteEnabled: true);

    internal ISilkGraphicsPipeline GetOrCreateMeshPipelineWithState(
        SilkShaderPermutationId permutation,
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode,
        SilkTopologyKind topologyKind,
        SilkBlendMode blendMode,
        bool depthWriteEnabled)
    {
        DeviceGenerationKey generation = ReadDeviceGeneration(_device);
        SilkShaderPermutationId canonical = permutation.CanonicalizeForPipeline();
        PipelineCacheKey key = new(
            canonical,
            CreateVertexLayoutKey(vertexLayout),
            colorFormat,
            depthFormat,
            cullMode,
            topologyKind,
            blendMode,
            depthWriteEnabled,
            _shaderFormat,
            generation);

        lock (_gate)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            if (generation != _generation)
            {
                DisposeEntries();
                _generation = generation;
            }

            if (!_entries.TryGetValue(key, out CachedPipelineEntry? entry))
            {
                entry = CreateEntry(
                    canonical,
                    canonical.CreateMeshBindingLayout(),
                    vertexLayout,
                    colorFormat,
                    depthFormat,
                    cullMode,
                    topologyKind,
                    blendMode,
                    depthWriteEnabled);
                _entries.Add(key, entry);
            }

            return entry.AcquireLease();
        }
    }

    internal ISilkGraphicsPipeline GetOrCreateSampledVolumePipeline(
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode = SilkCullMode.None,
        SilkTopologyKind topologyKind = SilkTopologyKind.TriangleList,
        SilkBlendMode blendMode = SilkBlendMode.None,
        bool depthWriteEnabled = true)
    {
        DeviceGenerationKey generation = ReadDeviceGeneration(_device);
        PipelineCacheKey key = new(
            "sampled-volume-density",
            CreateVertexLayoutKey(vertexLayout),
            colorFormat,
            depthFormat,
            cullMode,
            topologyKind,
            blendMode,
            depthWriteEnabled,
            _shaderFormat,
            generation);

        lock (_gate)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            if (generation != _generation)
            {
                DisposeEntries();
                _generation = generation;
            }

            if (!_entries.TryGetValue(key, out CachedPipelineEntry? entry))
            {
                entry = CreateEntry(
                    SilkShaderPermutationId.None,
                    SilkBindingLayoutDescriptor.SampledVolumeParameters,
                    vertexLayout,
                    colorFormat,
                    depthFormat,
                    cullMode,
                    topologyKind,
                    blendMode,
                    depthWriteEnabled,
                    sampledVolumeFragment: true);
                _entries.Add(key, entry);
            }

            return entry.AcquireLease();
        }
    }

    /// <summary>Gets or creates a runtime material pipeline from compiled shader descriptors.</summary>
    internal ISilkGraphicsPipeline GetOrCreateMaterialPipeline(
        SilkMaterialShaderProgram materialProgram,
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode = SilkCullMode.None,
        SilkTopologyKind topologyKind = SilkTopologyKind.TriangleList,
        SilkBlendMode blendMode = SilkBlendMode.None,
        bool depthWriteEnabled = true)
    {
        materialProgram.Validate();
        DeviceGenerationKey generation = ReadDeviceGeneration(_device);
        PipelineCacheKey key = new(
            materialProgram.CacheHash,
            CreateVertexLayoutKey(vertexLayout),
            colorFormat,
            depthFormat,
            cullMode,
            topologyKind,
            blendMode,
            depthWriteEnabled,
            _shaderFormat,
            generation);

        lock (_gate)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            if (generation != _generation)
            {
                DisposeEntries();
                _generation = generation;
            }

            if (!_entries.TryGetValue(key, out CachedPipelineEntry? entry))
            {
                entry = CreateEntry(
                    materialProgram,
                    vertexLayout,
                    colorFormat,
                    depthFormat,
                    cullMode,
                    topologyKind,
                    blendMode,
                    depthWriteEnabled);
                _entries.Add(key, entry);
            }

            return entry.AcquireLease();
        }
    }

    /// <inheritdoc/>
    public void Dispose()
    {
        lock (_gate)
        {
            if (_disposed)
            {
                return;
            }

            _disposed = true;
            DisposeEntries();
        }
    }

    private CachedPipelineEntry CreateEntry(
        SilkShaderPermutationId permutation,
        SilkBindingLayoutDescriptor bindingLayoutDescriptor,
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode,
        SilkTopologyKind topologyKind,
        SilkBlendMode blendMode,
        bool depthWriteEnabled,
        bool sampledVolumeFragment = false)
    {
        ISilkGraphicsShaderModule? vertexShader = null;
        ISilkGraphicsShaderModule? fragmentShader = null;
        ISilkGraphicsBindingLayout? bindingLayout = null;
        ISilkGraphicsShaderProgram? program = null;
        ISilkGraphicsPipeline? pipeline = null;
        try
        {
            vertexShader = _device.CreateShaderModule(
                SilkCheckedShaderAssets.LoadMeshVertex(_shaderFormat, permutation));
            // The sampled density volume is its own checked fragment program rather
            // than a switch inside the shared mesh permutation. A backend root
            // signature or pipeline layout must declare every resource its shader
            // binary references, so a volume texture compiled into the shared
            // fragment binary would have to be declared by every ordinary mesh
            // pipeline that never samples a volume -- which D3D12 rejects outright.
            fragmentShader = _device.CreateShaderModule(
                sampledVolumeFragment
                    ? SilkCheckedShaderAssets.LoadMeshVolumeFragment(_shaderFormat)
                    : SilkCheckedShaderAssets.LoadMeshFragment(_shaderFormat, permutation));
            bindingLayout = _device.CreateBindingLayout(bindingLayoutDescriptor);
            program = _device.CreateShaderProgram(new SilkShaderProgramDescriptor(
                vertexShader,
                fragmentShader,
                bindingLayout));
            pipeline = _device.CreateGraphicsPipeline(new SilkGraphicsPipelineDescriptor(
                program,
                vertexLayout,
                colorFormat,
                depthFormat,
                cullMode,
                topologyKind)
            {
                BlendMode = blendMode,
                DepthWriteEnabled = depthWriteEnabled,
            });
            return new CachedPipelineEntry(
                vertexShader,
                fragmentShader,
                bindingLayout,
                program,
                pipeline);
        }
        catch
        {
            pipeline?.Dispose();
            program?.Dispose();
            bindingLayout?.Dispose();
            fragmentShader?.Dispose();
            vertexShader?.Dispose();
            throw;
        }
    }

    private CachedPipelineEntry CreateEntry(
        SilkMaterialShaderProgram materialProgram,
        SilkVertexLayoutDescriptor vertexLayout,
        SilkTextureFormat colorFormat,
        SilkTextureFormat depthFormat,
        SilkCullMode cullMode,
        SilkTopologyKind topologyKind,
        SilkBlendMode blendMode,
        bool depthWriteEnabled)
    {
        ISilkGraphicsShaderModule? vertexShader = null;
        ISilkGraphicsShaderModule? fragmentShader = null;
        ISilkGraphicsBindingLayout? bindingLayout = null;
        ISilkGraphicsShaderProgram? program = null;
        ISilkGraphicsPipeline? pipeline = null;
        try
        {
            vertexShader = _device.CreateShaderModule(materialProgram.VertexShader);
            fragmentShader = _device.CreateShaderModule(materialProgram.FragmentShader);
            bindingLayout = _device.CreateBindingLayout(materialProgram.BindingLayout);
            program = _device.CreateShaderProgram(new SilkShaderProgramDescriptor(
                vertexShader,
                fragmentShader,
                bindingLayout));
            pipeline = _device.CreateGraphicsPipeline(new SilkGraphicsPipelineDescriptor(
                program,
                vertexLayout,
                colorFormat,
                depthFormat,
                cullMode,
                topologyKind)
            {
                BlendMode = blendMode,
                DepthWriteEnabled = depthWriteEnabled,
            });
            return new CachedPipelineEntry(
                vertexShader,
                fragmentShader,
                bindingLayout,
                program,
                pipeline);
        }
        catch
        {
            pipeline?.Dispose();
            program?.Dispose();
            bindingLayout?.Dispose();
            fragmentShader?.Dispose();
            vertexShader?.Dispose();
            throw;
        }
    }

    private static string CreateVertexLayoutKey(SilkVertexLayoutDescriptor layout)
    {
        layout.Validate();
        var builder = new StringBuilder();
        builder.Append(layout.Stride);
        foreach (SilkVertexAttributeDescriptor attribute in layout.Attributes)
        {
            builder
                .Append('|')
                .Append((int)attribute.Semantic)
                .Append(':')
                .Append(attribute.Location)
                .Append(':')
                .Append(attribute.Offset)
                .Append(':')
                .Append((int)attribute.Format);
        }

        return builder.ToString();
    }

    private static DeviceGenerationKey ReadDeviceGeneration(ISilkGraphicsDevice device)
    {
        ulong pickGeneration = device is ISilkPickingGraphicsDevice pickingDevice
            ? pickingDevice.PickDeviceGeneration
            : 0;
        ulong selectionGeneration = device is ISilkSelectionOutlineGraphicsDevice outlineDevice
            ? outlineDevice.SelectionOutlineDeviceGeneration
            : 0;
        return new DeviceGenerationKey(pickGeneration, selectionGeneration);
    }

    private void DisposeEntries()
    {
        foreach (CachedPipelineEntry entry in _entries.Values)
        {
            entry.Dispose();
        }
        _entries.Clear();
    }

    private readonly record struct DeviceGenerationKey(
        ulong PickGeneration,
        ulong SelectionOutlineGeneration);

    private readonly record struct PipelineCacheKey(
        object ShaderIdentity,
        string VertexLayout,
        SilkTextureFormat ColorFormat,
        SilkTextureFormat DepthFormat,
        SilkCullMode CullMode,
        SilkTopologyKind TopologyKind,
        SilkBlendMode BlendMode,
        bool DepthWriteEnabled,
        SilkShaderBinaryFormat ShaderFormat,
        DeviceGenerationKey Generation);

    private sealed class CachedPipelineEntry(
        ISilkGraphicsShaderModule vertexShader,
        ISilkGraphicsShaderModule fragmentShader,
        ISilkGraphicsBindingLayout bindingLayout,
        ISilkGraphicsShaderProgram program,
        ISilkGraphicsPipeline pipeline)
    {
        private readonly object _gate = new();
        private int _leaseCount;
        private bool _disposeRequested;
        private bool _nativeReleased;

        public ISilkGraphicsPipeline AcquireLease()
        {
            lock (_gate)
            {
                ObjectDisposedException.ThrowIf(_disposeRequested, typeof(SilkGraphicsPipelineCache));
                _leaseCount++;
            }
            return new CachedPipelineLease(this, pipeline);
        }

        public void Dispose()
        {
            bool release;
            lock (_gate)
            {
                if (_disposeRequested)
                {
                    return;
                }

                _disposeRequested = true;
                release = _leaseCount == 0 && !_nativeReleased;
                if (release)
                {
                    _nativeReleased = true;
                }
            }

            if (release)
            {
                ReleaseNative();
            }
        }

        private void ReleaseLease()
        {
            bool release;
            lock (_gate)
            {
                _leaseCount--;
                release = _disposeRequested && _leaseCount == 0 && !_nativeReleased;
                if (release)
                {
                    _nativeReleased = true;
                }
            }

            if (release)
            {
                ReleaseNative();
            }
        }

        private void ReleaseNative()
        {
            pipeline.Dispose();
            program.Dispose();
            bindingLayout.Dispose();
            fragmentShader.Dispose();
            vertexShader.Dispose();
        }

        private sealed class CachedPipelineLease(
            CachedPipelineEntry entry,
            ISilkGraphicsPipeline pipeline) : ISilkGraphicsPipelineLease
        {
            private CachedPipelineEntry? _entry = entry;

            public SilkGraphicsPipelineDescriptor Descriptor => pipeline.Descriptor;

            public ISilkGraphicsPipeline Pipeline => pipeline;

            public void Dispose() =>
                Interlocked.Exchange(ref _entry, null)?.ReleaseLease();
        }
    }
}

