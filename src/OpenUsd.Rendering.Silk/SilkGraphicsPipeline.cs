/// <summary>Mesh shader feature bits generated by the checked shader manifest.</summary>
[Flags]
public enum SilkShaderFeatures
{
    /// <summary>No optional mesh shader features.</summary>
    None = 0,

    /// <summary>Texture coordinates are available to the mesh shader.</summary>
    Uv = 1,

    /// <summary>A base-color texture is bound.</summary>
    BaseColorMap = 2,

    /// <summary>A normal texture is bound.</summary>
    NormalMap = 4,

    /// <summary>
    /// A roughness texture is bound. The numeric value and the <c>roughmetal</c>
    /// artifact token are kept for API and artifact stability, but the slot drives
    /// roughness alone: metallic has its own <see cref="MetallicMap"/> bit, and the
    /// two are fully independent. A packed occlusion/roughness/metallic file simply
    /// sets both bits, because it reaches the renderer as two connections naming one
    /// asset and two different UsdUVTexture output channels.
    /// </summary>
    RoughnessMetallicMap = 8,

    /// <summary>An emissive texture is bound.</summary>
    EmissiveMap = 16,

    /// <summary>
    /// A metallic texture is bound. Independent of <see cref="RoughnessMetallicMap"/>
    /// in both directions: a metallic-only material sets this bit alone, and a
    /// roughness-only material never sets it, so neither input can disturb the other.
    /// </summary>
    MetallicMap = 32,

    /// <summary>An opacity texture is bound.</summary>
    OpacityMap = 64,

    /// <summary>An occlusion texture is bound.</summary>
    OcclusionMap = 128,

    /// <summary>A specular-color texture is bound.</summary>
    SpecularColorMap = 256,

    /// <summary>A clearcoat texture is bound.</summary>
    ClearcoatMap = 512,

    /// <summary>A clearcoat-roughness texture is bound.</summary>
    ClearcoatRoughnessMap = 1024,

    /// <summary>An index-of-refraction texture is bound.</summary>
    IorMap = 2048
}

/// <summary>Stable mesh shader permutation identifier.</summary>
public readonly record struct SilkShaderPermutationId
{
    private const SilkShaderFeatures KnownFeatures =
        SilkShaderFeatures.Uv |
        SilkShaderFeatures.BaseColorMap |
        SilkShaderFeatures.NormalMap |
        SilkShaderFeatures.RoughnessMetallicMap |
        SilkShaderFeatures.EmissiveMap |
        SilkShaderFeatures.MetallicMap |
        SilkShaderFeatures.OpacityMap |
        SilkShaderFeatures.OcclusionMap |
        SilkShaderFeatures.SpecularColorMap |
        SilkShaderFeatures.ClearcoatMap |
        SilkShaderFeatures.ClearcoatRoughnessMap |
        SilkShaderFeatures.IorMap;
    private const SilkShaderFeatures MapFeatures =
        SilkShaderFeatures.BaseColorMap |
        SilkShaderFeatures.NormalMap |
        SilkShaderFeatures.RoughnessMetallicMap |
        SilkShaderFeatures.EmissiveMap |
        SilkShaderFeatures.MetallicMap |
        SilkShaderFeatures.OpacityMap |
        SilkShaderFeatures.OcclusionMap |
        SilkShaderFeatures.SpecularColorMap |
        SilkShaderFeatures.ClearcoatMap |
        SilkShaderFeatures.ClearcoatRoughnessMap |
        SilkShaderFeatures.IorMap;

    /// <summary>Initializes a manifest-valid mesh shader permutation.</summary>
    public SilkShaderPermutationId(SilkShaderFeatures features)
    {
        ValidateFeatures(features);
        Features = features;
    }

    /// <summary>Gets the manifest feature bits.</summary>
    public SilkShaderFeatures Features { get; }

    /// <summary>Gets the no-feature mesh permutation.</summary>
    public static SilkShaderPermutationId None => new(SilkShaderFeatures.None);

    /// <summary>Gets the checked mesh vertex artifact stem.</summary>
    public string MeshVertexArtifactName =>
        GetVertexArtifactName();

    /// <summary>Gets the checked mesh fragment artifact stem.</summary>
    public string MeshFragmentArtifactName =>
        GetFragmentArtifactName();

    internal SilkBindingLayoutDescriptor CreateMeshBindingLayout()
    {
        if ((Features & MapFeatures) == 0)
        {
            return SilkBindingLayoutDescriptor.SceneParameters;
        }

        var slots = new List<SilkBindingSlot>();
        if ((Features & MapFeatures) != 0)
        {
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.BaseColorSamplerBinding,
                SilkBindingLayoutDescriptor.BaseColorTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.RoughnessMetallicSamplerBinding,
                SilkBindingLayoutDescriptor.RoughnessMetallicTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.MetallicSamplerBinding,
                SilkBindingLayoutDescriptor.MetallicTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.EmissiveSamplerBinding,
                SilkBindingLayoutDescriptor.EmissiveTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.OpacitySamplerBinding,
                SilkBindingLayoutDescriptor.OpacityTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.OcclusionSamplerBinding,
                SilkBindingLayoutDescriptor.OcclusionTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.SpecularColorSamplerBinding,
                SilkBindingLayoutDescriptor.SpecularColorTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.ClearcoatSamplerBinding,
                SilkBindingLayoutDescriptor.ClearcoatTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.ClearcoatRoughnessSamplerBinding,
                SilkBindingLayoutDescriptor.ClearcoatRoughnessTextureBinding);
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.IorSamplerBinding,
                SilkBindingLayoutDescriptor.IorTextureBinding);
        }
        AddTextureSlots(
            slots,
            SilkShaderFeatures.NormalMap,
            SilkBindingLayoutDescriptor.NormalSamplerBinding,
            SilkBindingLayoutDescriptor.NormalTextureBinding);
        if ((Features & MapFeatures) != 0)
        {
            // The material's single composite image, declared for every
            // MAP_MATERIAL pipeline because the checked binary references it in
            // every one of them; a material that binds no composite leaves the
            // slot at the shared stand-in, exactly as an unbound material map
            // does. Added last on purpose: descriptor offsets follow slot order,
            // so appending keeps every pre-existing offset where it was.
            AddTextureSlots(
                slots,
                SilkBindingLayoutDescriptor.CompositeSamplerBinding,
                SilkBindingLayoutDescriptor.CompositeTextureBinding);
        }
        return SilkBindingLayoutDescriptor.ForMaterial(slots);
    }

    internal SilkShaderPermutationId CanonicalizeForPipeline()
    {
        if ((Features & MapFeatures) == 0)
        {
            return this;
        }

        SilkShaderFeatures canonical =
            SilkShaderFeatures.Uv | SilkShaderFeatures.BaseColorMap;
        if ((Features & SilkShaderFeatures.NormalMap) != 0)
        {
            canonical |= SilkShaderFeatures.NormalMap;
        }
        return new SilkShaderPermutationId(canonical);
    }

    private static void ValidateFeatures(SilkShaderFeatures features)
    {
        if ((features & ~KnownFeatures) != 0)
        {
            throw new ArgumentOutOfRangeException(nameof(features));
        }
        if ((features & MapFeatures) != 0 &&
            (features & SilkShaderFeatures.Uv) == 0)
        {
            throw new ArgumentException(
                "Mesh texture-map shader features require SilkShaderFeatures.Uv.",
                nameof(features));
        }
    }

    private string GetVertexArtifactName()
    {
        const string baseName = "mesh.vertex";
        if ((Features & SilkShaderFeatures.Uv) == 0)
        {
            return baseName;
        }

        var suffix = new StringBuilder();
        AppendToken(suffix, Features, SilkShaderFeatures.Uv, "uv");
        AppendToken(suffix, Features, SilkShaderFeatures.NormalMap, "normal");
        return $"{baseName}.{suffix}";
    }

    private string GetFragmentArtifactName()
    {
        const string baseName = "mesh.fragment";
        if (Features == SilkShaderFeatures.None)
        {
            return baseName;
        }

        var suffix = new StringBuilder("uv");
        if ((Features & MapFeatures) != 0)
        {
            suffix.Append("+material");
        }
        if ((Features & SilkShaderFeatures.NormalMap) != 0)
        {
            suffix.Append("+normal");
        }
        return $"{baseName}.{suffix}";
    }

    private static void AddTextureSlots(
        List<SilkBindingSlot> slots,
        uint samplerBinding,
        uint textureBinding)
    {
        slots.Add(new SilkBindingSlot(
            0,
            samplerBinding,
            SilkBindingKind.Sampler,
            0,
            SilkShaderStageVisibility.Fragment));
        slots.Add(new SilkBindingSlot(
            0,
            textureBinding,
            SilkBindingKind.SampledTexture,
            0,
            SilkShaderStageVisibility.Fragment));
    }

    private void AddTextureSlots(
        List<SilkBindingSlot> slots,
        SilkShaderFeatures feature,
        uint samplerBinding,
        uint textureBinding)
    {
        if ((Features & feature) == 0)
        {
            return;
        }

        AddTextureSlots(slots, samplerBinding, textureBinding);
    }

    private static void AppendToken(
        StringBuilder suffix,
        SilkShaderFeatures features,
        SilkShaderFeatures feature,
        string token)
    {
        if ((features & feature) == 0)
        {
            return;
        }
        if (suffix.Length != 0)
        {
            suffix.Append('+');
        }
        suffix.Append(token);
    }
}

/// <summary>Describes one checked shader module.</summary>
public readonly record struct SilkShaderModuleDescriptor(
    SilkShaderStage Stage,
    SilkShaderBinaryFormat Format,
    string EntryPoint,
    ReadOnlyMemory<byte> Code)
{
    /// <summary>Validates module code and entry point.</summary>
    public void Validate()
    {
        if (!Enum.IsDefined(Stage))
        {
            throw new ArgumentOutOfRangeException(nameof(Stage));
        }
        if (!Enum.IsDefined(Format))
        {
            throw new ArgumentOutOfRangeException(nameof(Format));
        }
        ArgumentException.ThrowIfNullOrWhiteSpace(EntryPoint);
        if (Code.IsEmpty)
        {
            throw new ArgumentException("Shader code cannot be empty.", nameof(Code));
        }
    }
}

