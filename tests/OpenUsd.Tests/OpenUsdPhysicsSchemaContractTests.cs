    [Test]
    public async Task CoverageMatrixStatesEveryDomainAsCoveredOrAsAnExplicitGap()
    {
        using JsonDocument definition = ReadJson(DefinitionPath());
        JsonElement gaps = definition.RootElement.GetProperty("gaps");

        await Assert.That(gaps.GetArrayLength()).IsGreaterThan(0)
            .Because("the plan requires physics domains to be stated, not silently missing.");

        Dictionary<string, bool> coverage = [];
        foreach (JsonElement domain in gaps.EnumerateArray())
        {
            string name = domain.GetProperty("domain").GetString()!;
            await Assert.That(name).IsNotEmpty();
            await Assert.That(domain.GetProperty("reason").GetString()).IsNotEmpty()
                .Because($"'{name}' must say why it is or is not covered.");
            coverage[name] = domain.GetProperty("covered").GetBoolean();
        }

        await Assert.That(coverage["characterControllers"]).IsTrue();
        await Assert.That(coverage["vehicles"]).IsTrue();
        await Assert.That(coverage["articulationTendons"]).IsTrue();
        await Assert.That(coverage["particles"]).IsTrue();
        await Assert.That(coverage["deformables"]).IsTrue();
        await Assert.That(coverage["attachments"]).IsTrue();
        await Assert.That(coverage.Values.Any(covered => !covered)).IsFalse()
            .Because("option B requires every agreed domain to be representable by openUsdPhysics:* schemas.");
    }

    private static JsonElement SinglePlugin(JsonDocument plugInfo)
    {
        JsonElement plugins = plugInfo.RootElement.GetProperty("Plugins");
        return plugins[0];
    }

    /// <summary>
    /// Maps a base class as written in <c>schema.usda</c> to the C++ name
    /// <c>usdGenSchema</c> records in <c>plugInfo.json</c>.
    /// </summary>
    private static string RegisteredBaseName(string declaredBase) => declaredBase switch
    {
        "APISchemaBase" => "UsdAPISchemaBase",
        "Typed" => "UsdTyped",
        _ => declaredBase,
    };

    private static JsonDocument ReadJson(string path) => JsonDocument.Parse(File.ReadAllText(path));

    /// <summary>
    /// Reads <c>plugInfo.json</c>, which OpenUSD allows to carry <c>#</c> comment lines
    /// that are not legal JSON.
    /// </summary>
    private static JsonDocument ReadPlugInfo()
    {
        string body = string.Join(
            '\n',
            File.ReadAllLines(GeneratedPath("plugInfo.json"))
                .Where(line => !line.TrimStart().StartsWith('#')));
        return JsonDocument.Parse(body);
    }

    private static string DefinitionPath() => SchemaRoot("openUsdPhysics.schema.json");

    private static string GeneratedPath(string fileName) =>
        Path.Combine(SchemaRoot("resources"), fileName);

    private static string SchemaRoot(string relativePath) =>
        Path.Combine(FindRepositoryRoot(), "schemas", "openUsdPhysics", relativePath);

    private static string FindRepositoryRoot()
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (File.Exists(Path.Combine(directory.FullName, "OpenUsd.slnx")))
            {
                return directory.FullName;
            }

            directory = directory.Parent;
        }

        throw new InvalidOperationException(
            $"Unable to locate the repository root from '{AppContext.BaseDirectory}'.");
    }
