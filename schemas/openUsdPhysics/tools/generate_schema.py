"""Generates the codeless openUsdPhysics schema artifacts.

`openUsdPhysics.schema.json` is the single source of truth. This script emits, all
from that one file:

  schema.usda                            the usdGenSchema input
  resources/plugInfo.json                the codeless plugin registration
  resources/generatedSchema.usda         the flattened schema registry layer
  precedence-manifest.json               the property/source resolution manifest
  src/OpenUsd.Physics/Schema/*.g.cs      typed managed facades and property tokens
  src/OpenUsd.Physics/PublicAPI.Unshipped.txt
                                         merged public API entries for the facades

Property types are restricted to the set `OpenUsd.UsdPrim` round-trips through its
generic typed accessors, so the managed facades need no new interop.

`usdGenSchema` remains the canonical producer of the two `resources/` files. It needs
a USD build with Python bindings, which this repository does not vendor, so this
script produces the same artifacts deterministically in the meantime. When a USD
Python build becomes available, run `usdGenSchema schema.usda resources` and the
output should be equivalent; `OpenUsdPhysicsSchemaContractTests` guards the
consistency of whichever producer wrote the files.

Usage:
    python schemas/openUsdPhysics/tools/generate_schema.py [--check]

`--check` writes nothing and fails when any artifact is out of date.
"""

