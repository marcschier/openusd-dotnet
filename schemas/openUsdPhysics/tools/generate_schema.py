def escape_csharp(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def render_public_api_lines(definition: dict) -> list:
    lines = []
    for cls in definition["classes"]:
        typed = cls["kind"] == "concreteTyped"
        full = f'{CSHARP_NAMESPACE}.{cls["name"]}'
        lines.append(full)
        lines.append(f'{full}.{cls["name"]}() -> void')
        lines.append(f"{full}.Prim.get -> OpenUsd.UsdPrim")
        lines.append(
            f'const {full}.SchemaIdentifier = "{cls["name"]}" -> string!')
        if typed:
            lines.append(
                f"static {full}.Define(OpenUsd.UsdStage! stage, string! path) -> {full}")
            lines.append(f"static {full}.IsA(OpenUsd.UsdPrim prim) -> bool")
        else:
            lines.append(f"static {full}.Has(OpenUsd.UsdPrim prim) -> bool")
        lines.append(f"static {full}.Wrap(OpenUsd.UsdPrim prim) -> {full}")
        for prop in sorted_properties(cls):
            member = member_name(prop)
            if prop["type"] == "rel":
                lines.append(f"{full}.Clear{member}() -> void")
                lines.append(f"{full}.Get{member}() -> string![]!")
                lines.append(f"{full}.Set{member}(string![]! targets) -> void")
                continue
            api_type = CSHARP_TYPES[prop["type"]][1]
            lines.append(f"{full}.{member}.get -> {api_type}")
            lines.append(f"{full}.{member}.set -> void")

    tokens = f"{CSHARP_NAMESPACE}.{CSHARP_TOKENS_CLASS}"
    lines.append(tokens)
    lines.append(
        f'const {tokens}.PluginName = "{definition["library"]["name"]}" -> string!')
    lines.append(
        f'const {tokens}.PropertyNamespace = '
        f'"{definition["library"]["propertyNamespace"]}" -> string!')
    for cls in definition["classes"]:
        for prop in sorted_properties(cls):
            lines.append(
                f'const {tokens}.{token_name(prop)} = "{prop["name"]}" -> string!')

    catalog = f"{CSHARP_NAMESPACE}.{CSHARP_CATALOG_CLASS}"
    schema_type = f"{CSHARP_NAMESPACE}.OpenUsdPhysicsSchemaDescriptor"
    property_type = f"{CSHARP_NAMESPACE}.OpenUsdPhysicsPropertyDescriptor"
    lines.append(catalog)
    lines.append(
        f"static {catalog}.Schemas.get -> "
        f"System.Collections.Generic.IReadOnlyList<{schema_type}!>!")
    lines.append(
        f"static {catalog}.TryGetProperty(string! name, out {property_type}? descriptor) -> bool")
    lines.append(
        f"static {catalog}.TryGetSchema(string! identifier, out {schema_type}? descriptor) -> bool")
    for cls in definition["classes"]:
        lines.append(f'static {catalog}.{cls["className"]}.get -> {schema_type}!')
    return lines


def public_api_rank(line: str) -> int:
    if line.startswith("#"):
        return 0
    if line.startswith("~"):
        return 1
    if line.startswith("const "):
        return 2
    if line.startswith("static "):
        return 4
    return 3


def render_public_api(definition: dict, existing: str) -> str:
    owned_types = [f'{CSHARP_NAMESPACE}.{cls["name"]}' for cls in definition["classes"]]
    owned_types.append(f"{CSHARP_NAMESPACE}.{CSHARP_TOKENS_CLASS}")
    owned_types.append(f"{CSHARP_NAMESPACE}.{CSHARP_CATALOG_CLASS}")

    def is_owned(line: str) -> bool:
        symbol = line
        for prefix in ("~", "const ", "static ", "override ", "abstract ", "virtual "):
            while symbol.startswith(prefix):
                symbol = symbol[len(prefix):]
        for owned in owned_types:
            if symbol == owned or symbol.startswith(owned + "."):
                return True
        return False

    retained = [
        line for line in existing.splitlines()
        if line and not is_owned(line)
    ]
    merged = sorted(
        set(retained) | set(render_public_api_lines(definition)),
        key=lambda line: (public_api_rank(line), line))
    return "\n".join(merged) + "\n"


def write(path: Path, content: str, check: bool, stale: list) -> None:

    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return
    if check:
        stale.append(str(path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail instead of writing when an artifact is out of date.")
    arguments = parser.parse_args()

    definition = json.loads(DEFINITION_PATH.read_text(encoding="utf-8"))
    validate(definition)

    stale: list = []
    write(SCHEMA_ROOT / "schema.usda",
          render_schema_usda(definition), arguments.check, stale)
    write(SCHEMA_ROOT / "resources" / "generatedSchema.usda",
          render_generated_schema(definition), arguments.check, stale)
    write(SCHEMA_ROOT / "resources" / "plugInfo.json",
          render_plug_info(definition), arguments.check, stale)
    write(SCHEMA_ROOT / "precedence-manifest.json",
          render_precedence_manifest(definition), arguments.check, stale)
    write(CSHARP_SCHEMA_DIR / "OpenUsdPhysicsTokens.g.cs",
          render_tokens_csharp(definition), arguments.check, stale)
    write(CSHARP_SCHEMA_DIR / "OpenUsdPhysicsSchemas.g.cs",
          render_schemas_csharp(definition), arguments.check, stale)
    write(CSHARP_SCHEMA_DIR / "OpenUsdPhysicsPropertyCatalog.g.cs",
          render_catalog_csharp(definition), arguments.check, stale)

    existing_api = (
        PUBLIC_API_PATH.read_text(encoding="utf-8")
        if PUBLIC_API_PATH.exists() else "#nullable enable\n")
    write(PUBLIC_API_PATH,
          render_public_api(definition, existing_api), arguments.check, stale)

    if stale:
        print("Out-of-date schema artifacts:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        print(
            "Run python schemas/openUsdPhysics/tools/generate_schema.py",
            file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
