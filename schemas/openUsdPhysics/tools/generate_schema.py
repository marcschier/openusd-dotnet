def format_float(value: float) -> str:
    """Formats a float the way USD writes one: no trailing '.0', 'inf' spelled out."""
    if isinstance(value, str):
        if value in ("inf", "-inf"):
            return value
        raise ValueError(f"Unsupported float literal '{value}'.")
    if value != value:
        raise ValueError("NaN defaults are not supported.")
    if value == int(value) and abs(value) < 1e16:
        return str(int(value))
    return repr(value)


def format_quoted(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def format_value(type_name: str, value, *, boolean_as_int: bool) -> str:
    if type_name == "bool":
        if boolean_as_int:
            return "1" if value else "0"
        return "true" if value else "false"
    if type_name == "int64":
        return str(int(value))
    if type_name == "double":
        return format_float(value)
    if type_name == "string":
        return format_quoted(value)
    if type_name == "token":
        return format_quoted(value)
    if type_name == "float3":
        return "(" + ", ".join(format_float(component) for component in value) + ")"
    if type_name == "token[]" or type_name == "string[]":
        return "[" + ", ".join(format_quoted(entry) for entry in value) + "]"
    if type_name == "int[]":
        return "[" + ", ".join(str(int(entry)) for entry in value) + "]"
    if type_name in ("float[]", "double[]"):
        return "[" + ", ".join(format_float(entry) for entry in value) + "]"
    if type_name == "bool[]":
        return "[" + ", ".join(
            ("1" if entry else "0") if boolean_as_int else ("true" if entry else "false")
            for entry in value) + "]"
    if type_name in ("float2[]", "float3[]"):
        return "[" + ", ".join(
            "(" + ", ".join(format_float(component) for component in tuple_value) + ")"
            for tuple_value in value) + "]"
    raise ValueError(f"Unsupported property type '{type_name}'.")


def sorted_properties(cls: dict) -> list:
    return sorted(cls["properties"], key=lambda prop: prop["name"])


def pascal_case(value: str) -> str:
    """Upper-cases the first character only, so camel humps and acronyms survive."""
    if not value:
        raise ValueError("Cannot derive a managed name from an empty segment.")
    return value[0].upper() + value[1:]


def member_name(prop: dict) -> str:
    return pascal_case(prop["name"].split(":")[2])


def token_name(prop: dict) -> str:
    _, group, leaf = prop["name"].split(":")
    return pascal_case(group) + pascal_case(leaf)


def xml_doc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def validate(definition: dict) -> None:
    namespace = definition["library"]["propertyNamespace"]
    seen_classes = set()
    seen_tokens: dict = {}
    for cls in definition["classes"]:
        if cls["name"] in seen_classes:
            raise ValueError(f"Duplicate class '{cls['name']}'.")
        seen_classes.add(cls["name"])
        if not cls["name"].startswith(definition["library"]["prefix"]):
            raise ValueError(
                f"Class '{cls['name']}' must start with the library prefix.")
        if cls["name"] != definition["library"]["prefix"] + cls["className"]:
            raise ValueError(
                f"Class '{cls['name']}' does not match its className "
                f"'{cls['className']}'.")
        if cls["kind"] not in ("singleApplyAPI", "concreteTyped"):
            raise ValueError(f"Unsupported schema kind '{cls['kind']}'.")
        if cls["base"] not in BASE_CPP_CLASS:
            raise ValueError(f"Unsupported base '{cls['base']}'.")
        if (cls["kind"] == "singleApplyAPI") != cls["name"].endswith("API"):
            raise ValueError(
                f"Class '{cls['name']}' kind and name suffix disagree.")
        seen_properties = set()
        seen_members = set()
        for prop in cls["properties"]:
            name = prop["name"]
            if name in seen_properties:
                raise ValueError(f"Duplicate property '{name}' on {cls['name']}.")
            seen_properties.add(name)
            if not name.startswith(namespace + ":"):
                raise ValueError(
                    f"Property '{name}' is not in the '{namespace}' namespace.")
            if name.count(":") != 2:
                raise ValueError(
                    f"Property '{name}' must be '{namespace}:<group>:<name>'.")
            member = member_name(prop)
            if member in RESERVED_MEMBER_NAMES:
                raise ValueError(
                    f"Property '{name}' maps to reserved managed member '{member}'.")
            if member in seen_members:
                raise ValueError(
                    f"Property '{name}' collides with another managed member "
                    f"'{member}' on {cls['name']}.")
            seen_members.add(member)
            token = token_name(prop)
            if seen_tokens.setdefault(token, name) != name:
                raise ValueError(
                    f"Property '{name}' collides with '{seen_tokens[token]}' on the "
                    f"generated token constant '{token}'.")
            type_name = prop["type"]
            if type_name == "rel":
                if "default" in prop or prop.get("uniform"):
                    raise ValueError(
                        f"Relationship '{name}' cannot declare a default or uniform.")
                continue
            if type_name not in SCALAR_TYPES and type_name not in ARRAY_TYPES:
                raise ValueError(f"Unsupported type '{type_name}' on '{name}'.")
            if type_name not in CSHARP_TYPES or type_name not in CSHARP_ACCESSORS:
                raise ValueError(
                    f"Type '{type_name}' on '{name}' has no managed accessor.")
            if "default" not in prop:
                raise ValueError(f"Attribute '{name}' requires a default.")
            if "allowedTokens" in prop and prop["default"] not in prop["allowedTokens"]:
                raise ValueError(
                    f"Default of '{name}' is not one of its allowed tokens.")


def render_schema_usda(definition: dict) -> str:
    library = definition["library"]
    lines = ["#usda 1.0", "(", "    subLayers = ["]
    lines.extend(
        f"        @{sub_layer}@," for sub_layer in library["subLayers"][:-1])
    lines.append(f"        @{library['subLayers'][-1]}@")
    lines.append("    ]")
    lines.append(")")
    lines.append("")
    lines.append('over "GLOBAL" (')
    lines.append("    customData = {")
    lines.append(f'        string libraryName = "{library["name"]}"')
    lines.append(f'        string libraryPath = "{library["path"]}"')
    lines.append(f'        string libraryPrefix = "{library["prefix"]}"')
    lines.append("        bool skipCodeGeneration = true")
    lines.append("    }")
    lines.append(")")
    lines.append("{")
    lines.append("}")

    for cls in definition["classes"]:
        lines.append("")
        if cls["kind"] == "concreteTyped":
            lines.append(f'class {cls["name"]} "{cls["name"]}" (')
        else:
            lines.append(f'class "{cls["name"]}" (')
        lines.append("    customData = {")
        lines.append(f'        string className = "{cls["className"]}"')
        if cls["kind"] == "singleApplyAPI":
            lines.append('        token apiSchemaType = "singleApply"')
        lines.append("    }")
        lines.append(f'    doc = """{cls["doc"]}"""')
        lines.append("")
        lines.append(f'    inherits = </{cls["base"]}>')
        lines.append(")")
        lines.append("{")
        for index, prop in enumerate(sorted_properties(cls)):
            if index > 0:
                lines.append("")
            lines.extend(
                render_property(prop, boolean_as_int=False, include_doc=True))
        lines.append("}")

    lines.append("")
    return "\n".join(lines)


def render_property(prop: dict, *, boolean_as_int: bool, include_doc: bool) -> list:
    name = prop["name"]
    type_name = prop["type"]
    if type_name == "rel":
        declaration = f"    rel {name}"
    else:
        qualifier = "uniform " if prop.get("uniform") else ""
        value = format_value(
            type_name, prop["default"], boolean_as_int=boolean_as_int)
        declaration = f"    {qualifier}{type_name} {name} = {value}"

    metadata = []
    if "allowedTokens" in prop:
        allowed = ", ".join(format_quoted(token) for token in prop["allowedTokens"])
        metadata.append(f"        allowedTokens = [{allowed}]")
    if "displayName" in prop:
        metadata.append(f'        displayName = {format_quoted(prop["displayName"])}')
    if include_doc:
        metadata.append(f'        doc = """{prop["doc"]}"""')

    if not metadata:
        return [declaration]
    return [declaration + " ("] + metadata + ["    )"]


def render_generated_schema(definition: dict) -> str:
    lines = [GENERATED_HEADER.rstrip("\n")]
    for cls in definition["classes"]:
        lines.append("")
        if cls["kind"] == "concreteTyped":
            lines.append(f'class {cls["name"]} "{cls["name"]}"')
        else:
            lines.append(f'class "{cls["name"]}"')
        lines.append("{")
        for prop in sorted_properties(cls):
            lines.extend(
                render_property(prop, boolean_as_int=True, include_doc=False))
        lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_plug_info(definition: dict) -> str:
    library = definition["library"]
    types = {}
    for cls in definition["classes"]:
        types[cls["name"]] = {
            "autoGenerated": True,
            "bases": [BASE_CPP_CLASS[cls["base"]]],
            "schemaIdentifier": cls["name"],
            "schemaKind": cls["kind"],
        }
    info = {
        "Plugins": [
            {
                "Info": {"Types": types},
                "Name": library["name"],
                "ResourcePath": "resources",
                "Root": "..",
                "Type": "resource",
            }
        ]
    }
    body = json.dumps(info, indent=4, sort_keys=True, separators=(", ", ": "))
    return PLUGINFO_COMMENT + body + "\n"


def render_precedence_manifest(definition: dict) -> str:
    library = definition["library"]
    precedence = sorted(definition["precedence"], key=lambda entry: entry["rank"])
    properties = []
    for cls in definition["classes"]:
        for prop in sorted_properties(cls):
            group = prop["name"].split(":")[1]
            properties.append({
                "property": prop["name"],
                "schema": cls["name"],
                "schemaKind": cls["kind"],
                "group": group,
                "type": prop["type"],
                "uniform": bool(prop.get("uniform", False)),
                "sourceNamespace": library["propertyNamespace"],
                "source": "project",
                "rank": precedence[0]["rank"],
            })
    manifest = {
        "$schemaVersion": 1,
        "generatedBy": "schemas/openUsdPhysics/tools/generate_schema.py",
        "generatedFrom": "schemas/openUsdPhysics/openUsdPhysics.schema.json",
        "resolutionRule": (
            "For one simulated property, the strongest authored opinion wins: an "
            "openUsdPhysics:* opinion overrides a physx* opinion, which overrides a "
            "standard physics:* opinion. An unsupported extension property produces a "
            "property-specific diagnostic and never suppresses supported semantics on "
            "the same object."
        ),
        "namespaces": precedence,
        "gaps": definition["gaps"],
        "properties": properties,
        "counts": {
            "schemas": len(definition["classes"]),
            "properties": len(properties),
        },
    }
    return json.dumps(manifest, indent=2, sort_keys=False) + "\n"


def render_tokens_csharp(definition: dict) -> str:
    library = definition["library"]
    lines = [CSHARP_HEADER.rstrip("\n"), ""]
    lines.append(f"namespace {CSHARP_NAMESPACE};")
    lines.append("")
    lines.append("/// <summary>")
    lines.append(
        "/// Property names of the codeless <c>openUsdPhysics</c> schema plugin. Use these "
        "constants instead of")
    lines.append("/// spelling a namespaced property name at a call site.")
    lines.append("/// </summary>")
    lines.append(f"public static class {CSHARP_TOKENS_CLASS}")
    lines.append("{")
    lines.append(
        "    /// <summary>The property namespace every openUsdPhysics property lives in.</summary>")
    lines.append(
        f'    public const string PropertyNamespace = "{library["propertyNamespace"]}";')
    lines.append("")
    lines.append(
        "    /// <summary>The plugin name registered by the generated plugInfo.json.</summary>")
    lines.append(f'    public const string PluginName = "{library["name"]}";')
    for cls in definition["classes"]:
        for prop in sorted_properties(cls):
            lines.append("")
            lines.append(
                f'    /// <summary>The <c>{xml_doc(prop["name"])}</c> property of '
                f'<c>{cls["name"]}</c>.</summary>')
            lines.append(
                f'    public const string {token_name(prop)} = "{prop["name"]}";')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_property_members(cls: dict, prop: dict) -> list:
    name = prop["name"]
    member = member_name(prop)
    token = f"{CSHARP_TOKENS_CLASS}.{token_name(prop)}"
    doc = xml_doc(prop["doc"])
    if prop["type"] == "rel":
        return [
            "",
            f"    /// <summary>Gets the targets of <c>{xml_doc(name)}</c>. {doc}</summary>",
            f"    public string[] Get{member}() => _prim.GetRelationshipTargets({token});",
            "",
            f"    /// <summary>Replaces the targets of <c>{xml_doc(name)}</c>. {doc}</summary>",
            "    /// <param name=\"targets\">The prim paths to author as targets.</param>",
            f"    public void Set{member}(string[] targets) =>",
            f"        _prim.SetRelationshipTargets({token}, targets);",
            "",
            f"    /// <summary>Clears every target of <c>{xml_doc(name)}</c>.</summary>",
            f"    public void Clear{member}() => _prim.ClearRelationshipTargets({token});",
        ]

    csharp_type = CSHARP_TYPES[prop["type"]][0]
    getter, setter = CSHARP_ACCESSORS[prop["type"]]
    return [
        "",
        f"    /// <summary>Gets or sets <c>{xml_doc(name)}</c>. {doc}</summary>",
        f"    public {csharp_type} {member}",
        "    {",
        f"        get => _prim.{getter}({token});",
        f"        set => _prim.{setter}({token}, value);",
        "    }",
    ]


